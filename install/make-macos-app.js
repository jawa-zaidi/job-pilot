#!/usr/bin/env node
'use strict';

// Builds JobPilot.app — a real macOS application bundle, so JobPilot can be
// double-clicked from Finder, dragged to Applications, and gets its own Dock
// icon instead of asking anyone to open a Terminal.
//
// A .app is just a folder with a specific shape:
//
//   JobPilot.app/
//     Contents/
//       Info.plist          what macOS reads to know this is an app
//       PkgInfo             legacy four-char type/creator codes
//       MacOS/JobPilot      the executable macOS actually runs
//
// The executable is a small shell script with this checkout's path baked in,
// so the bundle keeps working after it's dragged to /Applications.
//
// Run directly:  npm run make-app
// Or from code:  require('./make-macos-app.js').ensureBundle()

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BUNDLE = path.join(ROOT, 'JobPilot.app');
const CONTENTS = path.join(BUNDLE, 'Contents');
const MACOS_DIR = path.join(CONTENTS, 'MacOS');
const EXECUTABLE = path.join(MACOS_DIR, 'JobPilot');
const PLIST = path.join(CONTENTS, 'Info.plist');
const PKGINFO = path.join(CONTENTS, 'PkgInfo');

function version() {
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version || '0.1.0';
  } catch {
    return '0.1.0';
  }
}

// Make a path safe to drop inside a single-quoted shell string.
function shellSingleQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

function infoPlist() {
  const v = version();
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleDisplayName</key>
	<string>JobPilot</string>
	<key>CFBundleExecutable</key>
	<string>JobPilot</string>
	<key>CFBundleIdentifier</key>
	<string>org.jobpilot.launcher</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>JobPilot</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>${v}</string>
	<key>CFBundleSignature</key>
	<string>????</string>
	<key>CFBundleVersion</key>
	<string>${v}</string>
	<key>LSMinimumSystemVersion</key>
	<string>10.13</string>
	<key>NSHighResolutionCapable</key>
	<true/>
</dict>
</plist>
`;
}

function launcherScript() {
  const rootLiteral = shellSingleQuote(ROOT);
  return `#!/bin/bash
# Generated by install/make-macos-app.js — do not edit by hand.
# Rebuild with:  npm run make-app
#
# Runs JobPilot with no Terminal window. Anything that goes wrong is shown as a
# normal Mac dialog rather than a wall of text nobody asked for.

JP_ROOT=${rootLiteral}
JP_LOG="\${TMPDIR:-/tmp}/jobpilot-launcher.log"

jp_alert() {
  /usr/bin/osascript -e "display alert \\"JobPilot\\" message \\"$1\\" as critical" >/dev/null 2>&1
}

if [ ! -d "$JP_ROOT" ] || [ ! -f "$JP_ROOT/install/launch.js" ]; then
  jp_alert "The JobPilot folder has been moved or deleted, so this shortcut no longer knows where to look. Find the JobPilot folder, double-click JobPilot.command inside it, and a fresh copy of this app will be created."
  exit 1
fi

cd "$JP_ROOT" || exit 1

# shellcheck source=/dev/null
. "$JP_ROOT/install/find-node.sh"
JP_NODE="$(jp_find_node)" || JP_NODE=""

if [ -z "$JP_NODE" ]; then
  JP_ANSWER="$(/usr/bin/osascript -e 'display alert "One quick thing first" message "JobPilot needs Node.js — a free program that only ever has to be installed once. It takes about two minutes.

Click Get Node.js, then download the big green LTS button, open the file it downloads, and click Continue until it finishes.

Then open JobPilot again." buttons {"Not now", "Get Node.js"} default button "Get Node.js"' 2>/dev/null)"
  case "$JP_ANSWER" in
    *"Get Node.js"*) /usr/bin/open "https://nodejs.org/en/download" >/dev/null 2>&1 ;;
  esac
  exit 1
fi

export JOBPILOT_NOTIFY=1
"$JP_NODE" "$JP_ROOT/install/launch.js" >"$JP_LOG" 2>&1 &
JP_PID=$!

# Pass "Quit" from the Dock straight through to JobPilot so it shuts the server
# down tidily. (A hard Force Quit can't be caught here — launch.js notices it
# has been orphaned and stops by itself.)
trap 'kill -TERM "$JP_PID" 2>/dev/null' TERM INT

wait "$JP_PID"
JP_STATUS=$?
if [ "$JP_STATUS" -gt 128 ]; then
  wait "$JP_PID" 2>/dev/null
  JP_STATUS=$?
fi

# 130 = Ctrl+C, 143 = SIGTERM. Both mean "the user quit", not "it broke".
if [ "$JP_STATUS" -ne 0 ] && [ "$JP_STATUS" -ne 130 ] && [ "$JP_STATUS" -ne 143 ]; then
  jp_alert "JobPilot stopped unexpectedly. The technical details are in this file: $JP_LOG"
fi

exit "$JP_STATUS"
`;
}

// Read the JP_ROOT baked into an existing bundle, so we can spot a bundle left
// pointing at a folder that has since moved.
function bakedRoot() {
  try {
    const script = fs.readFileSync(EXECUTABLE, 'utf8');
    const match = script.match(/^JP_ROOT='((?:[^']|'\\'')*)'$/m);
    if (!match) return null;
    return match[1].replace(/'\\''/g, `'`);
  } catch {
    return null;
  }
}

function writeIfChanged(file, contents) {
  try {
    if (fs.readFileSync(file, 'utf8') === contents) return false;
  } catch { /* missing or unreadable — write it */ }
  fs.writeFileSync(file, contents);
  return true;
}

/**
 * Create or repair JobPilot.app. Safe to call on every launch: it only writes
 * when something actually differs, and it never touches anything outside the
 * bundle folder.
 */
function ensureBundle({ quiet = false } = {}) {
  if (process.platform !== 'darwin') {
    if (!quiet) console.log('  JobPilot.app is a macOS thing — nothing to do here.');
    return { built: false, path: null };
  }

  const existed = fs.existsSync(EXECUTABLE);
  const stale = existed && bakedRoot() !== ROOT;

  fs.mkdirSync(MACOS_DIR, { recursive: true });

  let changed = false;
  changed = writeIfChanged(PLIST, infoPlist()) || changed;
  changed = writeIfChanged(PKGINFO, 'APPL????') || changed;
  changed = writeIfChanged(EXECUTABLE, launcherScript()) || changed;

  // The executable bit is what makes the folder a launchable app.
  fs.chmodSync(EXECUTABLE, 0o755);

  if (changed) {
    // Nudge LaunchServices so Finder picks up the new bundle straight away.
    const now = new Date();
    try { fs.utimesSync(BUNDLE, now, now); } catch { /* cosmetic only */ }
  }

  if (!quiet) {
    if (!existed) console.log(`  ✓ Created ${BUNDLE}`);
    else if (stale) console.log(`  ✓ Repaired ${BUNDLE} (it was pointing at an old folder)`);
    else if (changed) console.log(`  ✓ Updated ${BUNDLE}`);
    else console.log(`  ✓ ${BUNDLE} is already up to date`);
    console.log('    Drag it to your Applications folder if you like.');
  }

  return { built: !existed, repaired: stale, path: BUNDLE };
}

module.exports = { ensureBundle, BUNDLE };

if (require.main === module) {
  ensureBundle({ quiet: false });
}
